export function theme({ name, file, palette: { colors } }: Variant): string {
  const named = Object.fromEntries(names.map((name) => [name, name])) as Colors;
  const sheet = Object.entries(ui(named, colors));
  const shared = sheet.filter(([key]) => key.startsWith("*."));
  const specific = sheet.filter(([key]) => !key.startsWith("*."));
  return json({
    name,
    dark: true,
    author: "steelesh",
    parentTheme,
    editorScheme: `/${file}.xml`,
    colors: Object.fromEntries(names.map((name) => [name, colors[name]])),
    ui: { "*": Object.fromEntries(shared.map(([key, value]) => [key.slice(2), value])), ...Object.fromEntries(specific) },
    icons: { ColorPalette: icons(colors), ...folderReplacements(), ...fileReplacements() },
  });
}
